KS.lang = localStorage.getItem("kaamsetu_lang") || "en";

KS.t = function (key) {
  return (KS.DICT[KS.lang] && KS.DICT[KS.lang][key]) || KS.DICT.en[key] || key;
};

KS.setLanguage = function (lang) {
  if (!KS.DICT[lang]) return;
  KS.lang = lang;
  localStorage.setItem("kaamsetu_lang", lang);
  document.querySelectorAll(".lang-picker").forEach((sel) => (sel.value = lang));

  // Trigger Google Translate for 100% full-page translation
  const combo = document.querySelector(".goog-te-combo");
  if (combo) {
    combo.value = lang;
    combo.dispatchEvent(new Event("change"));
  }
};
